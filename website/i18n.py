def translator(language: str):
    """Return a ``t(key, **kwargs)`` callable for the given language."""
    strings = TRANSLATIONS.get(language, TRANSLATIONS["en"])
    fallback = TRANSLATIONS["en"]

    def t(key: str, **kwargs) -> str:
        # "{count} chapters" reads badly at one; use the singular form when a
        # language provides one.
        if kwargs.get("count") == 1 and (strings.get(key + "_one") or fallback.get(key + "_one")):
            key = key + "_one"
        template = strings.get(key) or fallback.get(key) or key
        if kwargs:
            try:
                return template.format(**kwargs)
            except (KeyError, IndexError):
                return template
        return template

    return t


def language_name(code: str) -> str:
    return LANGUAGE_NAMES.get(code, code.upper())


def text_direction(code: str) -> str:
    return "rtl" if code in RTL_LANGUAGES else "ltr"
